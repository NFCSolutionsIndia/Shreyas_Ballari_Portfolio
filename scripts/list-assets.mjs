// Lists every image, video, 3D model and document in public/ and shows which code files use it.
//
//   pnpm assets            print the list in the terminal
//   pnpm assets --write    also save it to docs/assets-list.md
//
// A file marked "not used" is shipped with the site but no code points at it: check it, then
// either use it or delete it. Only Node's own modules are used, nothing to install.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep, extname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const WEB = fileURLToPath(new URL('..', import.meta.url));
const PUBLIC = join(WEB, 'public');
const SRC = join(WEB, 'src');
const OUT = join(WEB, 'docs', 'assets-list.md');

const KINDS = {
  Image: ['.jpg', '.jpeg', '.png', '.webp', '.avif', '.gif', '.svg', '.hdr', '.exr'],
  Video: ['.mp4', '.webm', '.mov'],
  '3D model': ['.glb', '.gltf', '.bin'],
  Document: ['.pdf'],
};
const kindOf = (file) => Object.keys(KINDS).find((k) => KINDS[k].includes(extname(file).toLowerCase())) ?? 'Other';
// Plumbing files that are not media; skip them.
const SKIP = new Set(['.gitkeep', 'robots.txt', 'site.webmanifest']);

const walk = (dir) =>
  readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = join(dir, e.name);
    if (e.isDirectory()) return p.includes(`${sep}mediapipe`) ? [] : walk(p);
    return SKIP.has(e.name) || e.name.endsWith('.md') || e.name.endsWith('.json') ? [] : [p];
  });

const sources = walk(SRC)
  .filter((p) => /\.(tsx?|css)$/.test(p))
  .concat(join(WEB, 'index.html'))
  .map((p) => ({ file: relative(WEB, p).split(sep).join('/'), text: readFileSync(p, 'utf8') }));

const size = (bytes) => (bytes > 1e6 ? `${(bytes / 1e6).toFixed(1)} MB` : `${Math.max(1, Math.round(bytes / 1e3))} KB`);

const rows = walk(PUBLIC)
  .map((p) => {
    const path = relative(PUBLIC, p).split(sep).join('/');
    const name = basename(path);
    const stem = name.split('.')[0];
    // Matched by full path, then file name, then the bare name in quotes (code that builds paths
    // with a helper, for example J('academy') for assets/journey/academy.placeholder.jpg).
    const users = sources
      .filter(({ text }) => text.includes(path) || text.includes(name) || text.includes(`'${stem}'`))
      .map(({ file }) => file.replace(/^src\//, ''));
    return { path, folder: path.split('/').slice(0, -1).join('/') || '(top level)', kind: kindOf(path), bytes: statSync(p).size, users };
  })
  .sort((a, b) => a.path.localeCompare(b.path));

// The 3D house loads its furniture by folder name, so count those as used by the house code.
for (const r of rows) {
  if (r.users.length === 0 && r.path.startsWith('assets/house/')) r.users.push('portfolios/creative/spatial/house (by folder)');
}

const unused = rows.filter((r) => r.users.length === 0);
const total = rows.reduce((n, r) => n + r.bytes, 0);

const md = [
  '# Every image, video and model on the site',
  '',
  'Generated by `pnpm assets --write`. Do not edit by hand: run the command again after adding or removing files.',
  '',
  `${rows.length} files, ${size(total)} in total. ${unused.length ? `**${unused.length} not used by any code.**` : 'Every file is used.'}`,
  '',
  'Paths are inside `public/`. In the browser each one is at `<site address>/<path>`.',
  '',
];
for (const folder of [...new Set(rows.map((r) => r.folder))]) {
  const list = rows.filter((r) => r.folder === folder);
  md.push(`## ${folder}`, '', '| File | Type | Size | Used in |', '| --- | --- | --- | --- |');
  for (const r of list) {
    md.push(`| \`${r.path.split('/').pop()}\` | ${r.kind} | ${size(r.bytes)} | ${r.users.length ? r.users.map((u) => `\`${u}\``).join(', ') : '**not used**'} |`);
  }
  md.push('');
}

console.log(`\n${rows.length} media files in public (${size(total)})\n`);
// The terminal shows one line per top-level folder (assets/house is many furniture files), then
// each file for the smaller folders. The --write file lists everything.
const group = (r) => r.path.split('/').slice(0, r.path.startsWith('assets/') ? 2 : 1).join('/');
for (const g of [...new Set(rows.map(group))]) {
  const list = rows.filter((r) => group(r) === g);
  console.log(`${g}  (${list.length} files, ${size(list.reduce((n, r) => n + r.bytes, 0))})`);
  if (list.length <= 15) for (const r of list) console.log(`   ${r.kind.padEnd(9)} ${size(r.bytes).padStart(8)}  ${r.path.slice(g.length + 1) || r.path}${r.users.length ? '' : '   <- not used'}`);
}
console.log(unused.length ? `\nNot used by any code:\n${unused.map((r) => `   ${r.path}`).join('\n')}` : '\nEvery file is used by the code.');

if (process.argv.includes('--write')) {
  writeFileSync(OUT, md.join('\n'));
  console.log(`\nSaved the full list to docs/assets-list.md`);
}
